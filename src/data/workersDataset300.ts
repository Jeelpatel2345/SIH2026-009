export function getWorkersByCity(city: string): CertifiedWorker[] {
  return certifiedWorkers300.filter(w => w.city.toLowerCase() === city.toLowerCase());
}

export function getWorkersByService(service: string): CertifiedWorker[] {
  const norm = service.toLowerCase();
  return certifiedWorkers300.filter(w => w.service.toLowerCase().includes(norm));
}

export function getTopWorkers(service?: string, city?: string, limit = 5): CertifiedWorker[] {
  let list = certifiedWorkers300;
  if (service) {
    const sNorm = service.toLowerCase();
    list = list.filter(w => w.service.toLowerCase().includes(sNorm));
  }
  if (city && city.toLowerCase() !== 'all cities') {
    const cNorm = city.toLowerCase();
    list = list.filter(w => w.city.toLowerCase() === cNorm);
  }
  return list
    .filter(w => w.availability === 'Available')
    .sort((a, b) => b.rating - a.rating || b.reviewsCount - a.reviewsCount)
    .slice(0, limit);
}
